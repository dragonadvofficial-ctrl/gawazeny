  /// Translates [key] according to given [context] or [localeCode].
  static String tr(String key, {BuildContext? context, String? localeCode}) {
    String lang = localeCode ?? 'ar';
    if (context != null) {
      final locale = Localizations.maybeLocaleOf(context);
      if (locale != null) {
        lang = locale.languageCode;
      }
    }

    final langMap = _localizedValues[lang] ?? _localizedValues['ar']!;
    return langMap[key] ?? _localizedValues['ar']![key] ?? key;
  }

  /// Checks if current context is Arabic (RTL).
  static bool isArabic(BuildContext context) {
    return (Localizations.maybeLocaleOf(context)?.languageCode ?? 'ar') != 'en';
  }
}

/// Official LocalizationsDelegate for [AppTranslations] enabling standard Flutter localization.
class AppLocalizationsDelegate extends LocalizationsDelegate<AppTranslations> {
  const AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => ['ar', 'en'].contains(locale.languageCode);

  @override
  Future<AppTranslations> load(Locale locale) {
    return SynchronousFuture<AppTranslations>(AppTranslations());
  }

  @override
  bool shouldReload(AppLocalizationsDelegate old) => false;
}

/// Handy extension on [BuildContext] for easy string translation in widgets.
extension BuildContextTranslation on BuildContext {
  String tr(String key) => AppTranslations.tr(key, context: this);
  bool get isArabic => AppTranslations.isArabic(this);
}
